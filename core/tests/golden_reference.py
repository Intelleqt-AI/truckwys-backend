    if len(sys.argv) == 3 and sys.argv[1] == '--freeze':
        freeze(sys.argv[2])
        print('expected block frozen into', sys.argv[2])
    else:
        print(json.dumps(compute_expected(load(sys.argv[1]))['periods'], indent=2))
